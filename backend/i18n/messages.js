const formatMessage = (template, params = {}) => template.replace(/\{(\w+)\}/g, (_, key) => (
    params[key] === undefined || params[key] === null ? '' : String(params[key])
));

const translate = (locale, messageKey, messageParams = {}) => {
    const dictionary = messages[locale] || messages[DEFAULT_LOCALE];
    const fallbackDictionary = messages[DEFAULT_LOCALE];
    const template = dictionary[messageKey] || fallbackDictionary[messageKey] || messageKey;
    return formatMessage(template, messageParams);
};

