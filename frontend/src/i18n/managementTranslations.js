const getNestedValue = (object, path) =>
  path.split('.').reduce((currentValue, segment) => (currentValue && currentValue[segment] !== undefined ? currentValue[segment] : undefined), object);

const interpolate = (template, values = {}) =>
  template.replace(/\{\{(.*?)\}\}/g, (_, key) => {
    const value = values[key.trim()];
    return value === undefined || value === null ? '' : String(value);
  });

export const hasManagementTranslation = (language, key) => {
  const dictionary = managementTranslations[language] || managementTranslations.tr;
  return getNestedValue(dictionary, key) !== undefined || getNestedValue(managementTranslations.tr, key) !== undefined;
};

export const translateManagement = (language, key, values) => {
  const dictionary = managementTranslations[language] || managementTranslations.tr;
  const resolved = getNestedValue(dictionary, key) ?? getNestedValue(managementTranslations.tr, key);
  if (resolved === undefined) return undefined;
  return typeof resolved === 'string' ? interpolate(resolved, values) : resolved;
};

export default managementTranslations;



